export type CultivationPhraseKey = keyof typeof CULTIVATION_PHRASES

export function formatCultivationText(
  template: string,
  params: CultivationTextParams = {},
): string {
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (token, key: string) => {
    const value = params[key]
    return value === undefined ? token : String(value)
  })
}

export function formatCultivationPhrase(
  key: CultivationPhraseKey,
  params: CultivationTextParams = {},
): string {
  return formatCultivationText(CULTIVATION_PHRASES[key], params)
}

